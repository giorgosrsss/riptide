window.hydrateIcons = function (root = document) {
  root.querySelectorAll('i[data-icon]').forEach(el => {
    el.innerHTML = window.icon(el.dataset.icon)
    el.removeAttribute('data-icon')
    el.classList.add('ic')
  })
}
